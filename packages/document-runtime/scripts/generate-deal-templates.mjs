import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = join(packageRoot, '..', '..', 'docs', 'platform', 'office', 'deal');
const outputPath = join(
  packageRoot,
  'src',
  'domain',
  'generatedDealTemplates.ts',
);

const sources = {
  electronic_order: 'electronic-order.html',
  proforma: 'proforma-invoice.html',
  pilot_offer: 'pilot-offer.html',
};

const templates = Object.fromEntries(
  await Promise.all(
    Object.entries(sources).map(async ([type, fileName]) => [
      type,
      await readFile(join(sourceRoot, fileName), 'utf8'),
    ]),
  ),
);

const output = `/**
 * Generated by scripts/generate-deal-templates.mjs from docs/platform/office/deal.
 * Do not edit manually.
 */

export const GENERATED_DEAL_TEMPLATES = Object.freeze(${JSON.stringify(
  templates,
  null,
  2,
)} as const);
`;

await writeFile(outputPath, output, 'utf8');
